using System.Net.Http.Headers;
using System.Net.Http.Json;
using Application.Interfaces;
using Dapper;
using Infrastructure.Configurations;
using Infrastructure.Identity;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Options;
using Npgsql;
using Testcontainers.PostgreSql;
using Trader.Binance;

namespace Trader.IntegrationTests;

/// <summary>The real Trader host on a throwaway Postgres, with a fake Binance. Tokens are made by the API's own token services.</summary>
public sealed class TraderFixture : WebApplicationFactory<Program>, IAsyncLifetime
{
    public const string AdminRole = "Administrator";
    public const string JwtSecret = "signing-key-of-the-integration-tests-of-the-trader-0123456789";

    private static readonly JwtConfigurations Jwt = new() { Secret = JwtSecret, Issuer = "TradePulseApi", Audience = "TradePulseClient", DurationInMinutes = 30 };

    public string MasterKey { get; } = Convert.ToBase64String(System.Security.Cryptography.RandomNumberGenerator.GetBytes(32));

    public FakeBinance Binance { get; } = new();

    public string ConnectionString => _postgres.GetConnectionString();

    private readonly PostgreSqlContainer _postgres = new PostgreSqlBuilder("postgres:17-alpine").Build();

    public async ValueTask InitializeAsync()
    {
        await _postgres.StartAsync();

        // The audit log is made by the API's migrations; here just the part the Trader writes to.
        await using var connection = new NpgsqlConnection(ConnectionString);
        await connection.ExecuteAsync("""
            CREATE SCHEMA IF NOT EXISTS config;
            CREATE TABLE IF NOT EXISTS config.audit_log (
                "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "OccurredAt" timestamp NOT NULL, "UserName" varchar(256) NOT NULL,
                "Action" varchar(16) NOT NULL, "EntityType" varchar(32) NOT NULL, "EntityId" integer NOT NULL, "Summary" varchar(256) NOT NULL, "Details" text NULL);
            """);
    }

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        builder.UseSetting("ConnectionStrings:Vault", ConnectionString);
        builder.UseSetting("JwtConfigurations:Secret", Jwt.Secret);
        builder.UseSetting("JwtConfigurations:Issuer", Jwt.Issuer);
        builder.UseSetting("JwtConfigurations:Audience", Jwt.Audience);
        builder.UseSetting("AdminConfigurations:Role", AdminRole);
        builder.UseSetting("Vault:MasterKey", MasterKey);
        builder.UseSetting("RateLimiting:KeysPerMinute", "1000");
        builder.ConfigureServices(services =>
            services.AddHttpClient(BinanceClient.HttpClientName).ConfigurePrimaryHttpMessageHandler(() => Binance));
    }

    // ---- who is asking (tokens exactly as the API makes them)

    public sealed record Caller(Guid Id, string Name, string AccessToken, string Elevation);

    public Caller Administrator(string name = "admin") => MakeCaller(name, AdminRole);

    public Caller OrdinaryUser(string name = "ordinary") => MakeCaller(name, "User");

    private static Caller MakeCaller(string name, string role)
    {
        var id = Guid.NewGuid();
        var access = new JwtAccessTokenService(Options.Create(Jwt)).Create(new AuthenticatedUser(id, name, $"{name}@example.com", [role])).Token;
        var elevation = new JwtElevationTokenService(Options.Create(Jwt), TimeProvider.System).Create(id).Token;
        return new Caller(id, name, access, elevation);
    }

    public Task<HttpResponseMessage> SendAsync(HttpMethod method, string url, Caller? caller, object? body = null, bool elevated = true, string? elevation = null)
    {
        var request = new HttpRequestMessage(method, url) { Content = body is null ? null : JsonContent.Create(body) };
        if (caller is not null)
        {
            request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", caller.AccessToken);
            if (elevated || elevation is not null)
                request.Headers.Add("X-Elevation", elevation ?? caller.Elevation);
        }

        return CreateClient().SendAsync(request, TestContext.Current.CancellationToken);
    }

    public T Service<T>() where T : notnull => Services.GetRequiredService<T>();

    async ValueTask IAsyncDisposable.DisposeAsync()
    {
        await base.DisposeAsync();
        await _postgres.DisposeAsync();
    }
}
